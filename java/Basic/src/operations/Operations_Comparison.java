package operations;

public class Operations_Comparison {
    public static void main(String[] args) {
        byte a = 10;
        byte b = 5;
        byte c = 5;

        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a >= c);
        System.out.println(a <= b + c);
        System.out.println(b == c);
        System.out.println(b != c);

    }
}
