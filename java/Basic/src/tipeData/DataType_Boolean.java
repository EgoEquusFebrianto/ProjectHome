package tipeData;

public class DataType_Boolean {
    public static void main(String[] args) {
        // dalam number, jika variabel tidak diisi maka default adalah 0
        // untuk boolean, default variabel adalah false

        boolean benar = true;
        boolean salah = false;

        System.out.println(benar);
        System.out.println(salah);
    }
}
