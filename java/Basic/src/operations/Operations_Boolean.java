package operations;

public class Operations_Boolean {
    public static void main(String[] args) {
        boolean a = true;
        boolean b = true;
        boolean c = false;

        System.out.println(a && b);
        System.out.println(a && c);
        System.out.println(a || b);
        System.out.println(a || c);
        System.out.println(!a);
        System.out.println(!c);

    }
}
